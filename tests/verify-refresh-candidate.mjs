import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const workflow = await readFile(resolve(root, ".github/workflows/c7-usgs-water.yml"), "utf8");
const uploader = await readFile(resolve(root, "scripts/upload-c7-r2.mjs"), "utf8");
const packageJson = JSON.parse(await readFile(resolve(root, "package.json"), "utf8"));
const statePaths = JSON.parse(await readFile(resolve(root, "data/state-paths.json"), "utf8"));

assert.match(workflow, /workflow_dispatch:/);
assert.match(workflow, /schedule:/);
assert.match(workflow, /cron: ["']17 \*\/6 \* \* \*["']/);
assert.doesNotMatch(workflow, /pull_request:|push:/);
assert.match(workflow, /permissions:\n  contents: read/);
assert.match(workflow, /cancel-in-progress: false/);
assert.match(workflow, /timeout-minutes: 30/);
assert.match(workflow, /actions\/checkout@[a-f0-9]{40}/);
assert.match(workflow, /actions\/setup-node@[a-f0-9]{40}/);
assert.match(workflow, /--window-hours=24/);
assert.match(workflow, /--publication-minimum-sites=1/);
assert.match(workflow, /--schema-version=admatera-water-summary-v2/);
assert.match(workflow, /--include-metric-evidence/);
assert.match(workflow, /--omit-overall-sites/);
assert.doesNotMatch(workflow, /git\s+(add|commit|push)/);
assert.doesNotMatch(workflow, /0\.67|tdsEst|waterservices\.usgs\.gov/);
assert.match(workflow, /secrets\.USGS_API_KEY/);
assert.match(workflow, /secrets\.C7_R2_ACCESS_KEY_ID/);
assert.match(workflow, /secrets\.C7_R2_SECRET_ACCESS_KEY/);
assert.doesNotMatch(workflow, /C7_PREVIEW_TOKEN/);
assert.match(uploader, /admatera-maps-c7-private-preview-v1/);
assert.match(uploader, /IfNoneMatch: "\*"/);
assert.match(uploader, /promoted\/current\.json/);
assert.match(uploader, /pointer-last promotion|promoted pointer unchanged|await put\("promoted\/current\.json"/);
assert.equal(packageJson.dependencies["@aws-sdk/client-s3"], "3.1127.0");
assert.equal(statePaths.states.length, 52);
assert.equal(statePaths.states.filter((row) => row.state !== "PR").length, 51);
assert.equal(new Set(statePaths.states.map((row) => row.state)).size, 52);
assert.ok(statePaths.states.every((row) => /^[A-Z]{2}$/.test(row.state) && /^\d{2}$/.test(row.fips)));
console.log("MAP-DATA-012A workflow security contract: PASS");
